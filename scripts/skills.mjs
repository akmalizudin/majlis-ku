// Keep the Codex twins in step with the Claude sources. The Claude copy is the source of truth.
//   .claude/skills/<name>/SKILL.md  ->  .codex/skills/<name>/SKILL.md + agents/openai.yaml
//   .claude/agents/<name>.md        ->  .codex/agents/<name>.toml
//
// Usage:
//   node scripts/skills.mjs sync    regenerate the Codex twins
//   node scripts/skills.mjs check   exit 1 when a Codex twin is not an exact regeneration

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CLAUDE_DIR = join(".claude", "skills");
const CODEX_DIR = join(".codex", "skills");
const SKILL_FILE = "SKILL.md";
const OPENAI_YAML = join("agents", "openai.yaml");
const SHORT_DESCRIPTION_MAX = 110;
const ACRONYMS = { tdd: "TDD", pdpa: "PDPA" };
const CLAUDE_AGENTS = join(".claude", "agents");
const CODEX_AGENTS = join(".codex", "agents");
// Claude model tier -> Codex model, per playbook.md §12.
const CODEX_MODELS = { haiku: "gpt-6-luna", sonnet: "gpt-6-luna", opus: "gpt-6.1-sol" };

// Codex reads AGENTS.md. Lines that already name AGENTS.md are left alone.
export function toCodex(text) {
  return text
    .split("\n")
    .map((line) => (line.includes("AGENTS.md") ? line : line.replaceAll("CLAUDE.md", "AGENTS.md")))
    .join("\n");
}

export function frontmatter(text) {
  const match = text.replace(/\r\n/g, "\n").match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) return {};
  const fields = {};
  for (const line of match[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) fields[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return fields;
}

function short(description) {
  const first = description.split(/(?<=[.!?])\s/)[0].replace(/\.$/, "");
  return first.length <= SHORT_DESCRIPTION_MAX ? first : `${first.slice(0, SHORT_DESCRIPTION_MAX - 3).trimEnd()}...`;
}

export function openaiYaml(name, description) {
  const title = name
    .split("-")
    .map((word) => ACRONYMS[word] ?? word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
  const prompt = `Use $${name} to handle this Majlis Ku task.`;
  return [
    "interface:",
    `  display_name: ${JSON.stringify(title)}`,
    `  short_description: ${JSON.stringify(short(description))}`,
    `  default_prompt: ${JSON.stringify(prompt)}`,
    "",
    "policy:",
    "  allow_implicit_invocation: true",
    "",
  ].join("\n");
}

function skillNames(base) {
  const folder = join(ROOT, base);
  if (!existsSync(folder)) return [];
  return readdirSync(folder)
    .filter((n) => statSync(join(folder, n)).isDirectory())
    .sort();
}

function read(path) {
  return readFileSync(path, "utf8").replace(/\r\n/g, "\n");
}

// The SKILL.md text and openai.yaml text the Codex twin must have for a Claude skill.
function expectedTwin(name) {
  const source = read(join(ROOT, CLAUDE_DIR, name, SKILL_FILE));
  return [toCodex(source), openaiYaml(name, frontmatter(source).description ?? "")];
}

function agentNames(base) {
  const folder = join(ROOT, base);
  if (!existsSync(folder)) return [];
  return readdirSync(folder).filter((n) => n.endsWith(base === CLAUDE_AGENTS ? ".md" : ".toml")).map((n) => n.replace(/\.(md|toml)$/, "")).sort();
}

// The .toml text the Codex twin must have for a Claude agent.
export function expectedAgentTwin(name) {
  const source = read(join(ROOT, CLAUDE_AGENTS, `${name}.md`));
  const meta = frontmatter(source);
  const body = toCodex(source.replace(/^---\n[\s\S]*?\n---\n\n?/, "")).trimEnd();
  return [
    `# Codex twin of .claude/agents/${name}.md, generated by node scripts/skills.mjs sync. Edit the Claude copy.`,
    `name = ${JSON.stringify(name.replaceAll("-", "_"))}`,
    `description = ${JSON.stringify(meta.description ?? "")}`,
    `model = ${JSON.stringify(CODEX_MODELS[meta.model] ?? CODEX_MODELS.sonnet)}`,
    `model_reasoning_effort = ${JSON.stringify(meta.effort ?? "medium")}`,
    "developer_instructions = '''",
    body,
    "'''",
    "",
  ].join("\n");
}

function syncAgents() {
  const claude = agentNames(CLAUDE_AGENTS);
  mkdirSync(join(ROOT, CODEX_AGENTS), { recursive: true });
  for (const name of claude) writeFileSync(join(ROOT, CODEX_AGENTS, `${name}.toml`), expectedAgentTwin(name), "utf8");
  for (const name of agentNames(CODEX_AGENTS)) {
    if (!claude.includes(name)) {
      rmSync(join(ROOT, CODEX_AGENTS, `${name}.toml`), { force: true });
      console.log(`removed orphan Codex agent: ${name}`);
    }
  }
  console.log(`Synced ${claude.length} agents to ${CODEX_AGENTS}`);
}

function checkAgents(problems) {
  const claude = agentNames(CLAUDE_AGENTS);
  const codex = agentNames(CODEX_AGENTS);
  for (const n of codex) if (!claude.includes(n)) problems.push(`agent ${n}: exists under ${CODEX_AGENTS} but not under ${CLAUDE_AGENTS}`);
  for (const name of claude) {
    const meta = frontmatter(read(join(ROOT, CLAUDE_AGENTS, `${name}.md`)));
    if (meta.name !== name) problems.push(`agent ${name}: frontmatter name is ${JSON.stringify(meta.name)}, expected ${JSON.stringify(name)}`);
    if (!meta.description) problems.push(`agent ${name}: frontmatter description is missing`);
    if (!(meta.model in CODEX_MODELS)) problems.push(`agent ${name}: model must be one of ${Object.keys(CODEX_MODELS).join(", ")}`);
    const path = join(ROOT, CODEX_AGENTS, `${name}.toml`);
    if (!existsSync(path)) problems.push(`agent ${name}: missing ${path}`);
    else if (read(path) !== expectedAgentTwin(name)) problems.push(`agent ${name}: .toml differs from the Claude agent (run node scripts/skills.mjs sync)`);
  }
  return claude.length;
}

function sync() {
  syncAgents();
  const claude = skillNames(CLAUDE_DIR);
  for (const name of claude) {
    const [skillText, yamlText] = expectedTwin(name);
    const target = join(ROOT, CODEX_DIR, name);
    mkdirSync(join(target, "agents"), { recursive: true });
    writeFileSync(join(target, SKILL_FILE), skillText, "utf8");
    writeFileSync(join(target, OPENAI_YAML), yamlText, "utf8");
  }
  for (const name of skillNames(CODEX_DIR)) {
    if (!claude.includes(name)) {
      rmSync(join(ROOT, CODEX_DIR, name), { recursive: true, force: true });
      console.log(`removed orphan Codex skill: ${name}`);
    }
  }
  console.log(`Synced ${claude.length} skills to ${CODEX_DIR}`);
  return 0;
}

function check() {
  const problems = [];
  const claude = skillNames(CLAUDE_DIR);
  const codex = skillNames(CODEX_DIR);
  for (const n of claude) if (!codex.includes(n)) problems.push(`${n}: missing under ${CODEX_DIR}`);
  for (const n of codex) if (!claude.includes(n)) problems.push(`${n}: exists under ${CODEX_DIR} but not under ${CLAUDE_DIR}`);
  for (const name of claude) {
    const source = join(ROOT, CLAUDE_DIR, name, SKILL_FILE);
    if (!existsSync(source)) {
      problems.push(`${name}: no ${SKILL_FILE} under ${CLAUDE_DIR}`);
      continue;
    }
    const meta = frontmatter(read(source));
    if (meta.name !== name) problems.push(`${name}: frontmatter name is ${JSON.stringify(meta.name)}, expected ${JSON.stringify(name)}`);
    if (!meta.description) problems.push(`${name}: frontmatter description is missing`);
    if (!codex.includes(name)) continue;
    const [skillText, yamlText] = expectedTwin(name);
    for (const [rel, expected] of [[SKILL_FILE, skillText], [OPENAI_YAML, yamlText]]) {
      const path = join(ROOT, CODEX_DIR, name, rel);
      if (!existsSync(path)) problems.push(`${name}: missing ${join(CODEX_DIR, name, rel)}`);
      else if (read(path) !== expected) problems.push(`${name}: ${rel} differs from the Claude skill (run node scripts/skills.mjs sync)`);
    }
  }
  const agents = checkAgents(problems);
  for (const p of problems) console.error(`skill-parity: ${p}`);
  if (problems.length) return 1;
  console.log(`skill-parity: ${claude.length} skills and ${agents} agents in sync`);
  return 0;
}

const command = process.argv[2];
if (command === "sync") process.exit(sync());
else if (command === "check") process.exit(check());
else {
  console.error("usage: node scripts/skills.mjs sync|check");
  process.exit(2);
}